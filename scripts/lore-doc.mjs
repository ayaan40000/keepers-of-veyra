// Builds the community lore guide in docs/lore/ from the game's own story data, so the guide quotes the canon exactly and
// never drifts from it. Run after any story change: npx vite-node scripts/lore-doc.mjs
// docs/lore/README.md (the front page) is written by hand and is not touched.
import fs from 'node:fs';
import path from 'node:path';
import { CHAPTERS } from '../src/data/chapters.js';
import { CODEX, CHARACTERS } from '../src/data/lore.js';
import { MODULES, SKILLS } from '../src/data/curriculum.js';
import { BEATS, SIDE_QUESTS } from '../src/data/quests.js';
import { EPILOGUE, GATE_TALK } from '../src/data/afteryear.js';
import { TABLETS, TREASURES, BOSSES } from '../src/data/crypt.js';
import { ITEMS, KINDS } from '../src/data/items.js';
import { TRIALS, TRIAL_ORDER, VAULT_ORDER } from '../src/data/trials.js';
import { FORGETTINGS, COACHES, ECHO_BEAT, ECHO_HOOK } from '../src/data/echo.js';
import { SEAM_LORE, SEAM_CHAPTER, EPILOGUE_TWO, SEAM_PEOPLE, FACE_DETAILS } from '../src/data/forgetting.js';
import { WF_BEATS } from '../src/data/wren.js';

const OUT = 'docs/lore';
const HEAD = '<!-- Generated by scripts/lore-doc.mjs from src/data. Do not edit here: change the story data and re-run the script. -->\n\n';
const SPOIL = '> **Spoilers.** This page reveals the story as it unfolds through the year. Read the world and district pages first if you want to discover it in the game.\n\n';
const name = (t) => String(t).replaceAll('{name}', 'the Keeper');
const para = (arr) => arr.map((t) => name(t).includes(' / ') ? name(t).split(' / ').map((l) => `> ${l}`).join('\n') : name(t)).join('\n\n');
const unlockText = (u) => (u === 'start' ? 'known from the start' : u.startsWith('gate:') ? `after the ${MODULES.find((m) => m.id === u.slice(5))?.district} is restored (month ${MODULES.find((m) => m.id === u.slice(5))?.month})`
  : u === 'seam:met' ? 'when the Keeper first meets the Great Forgetting (Chapter 13)' : u === 'seam:closed' ? 'when the Seam is closed (Chapter 13)'
  : u.startsWith('wren:beat:') ? `after Wren's story beat "${WF_BEATS.find((b) => b.id === u.slice(10))?.title}"` : u === 'wren:held:1' ? `once the Keeper has kept a detail from Wren's story` : u === 'wren:scene:face' ? `once the four details of Wren's mother's face are kept` : u === 'wren:scene:lamp' ? 'once the tune and the lamps are kept'
  : u.startsWith('side:') ? `after the side quest "${SIDE_QUESTS.find((q) => q.id === u.slice(5))?.title}"` : u.startsWith('trial:') ? `after passing "${TRIALS[u.slice(6)]?.title}"` : u);
const write = (file, body) => { fs.mkdirSync(OUT, { recursive: true }); fs.writeFileSync(path.join(OUT, file), HEAD + body.trim() + '\n'); console.log(file, body.split(/\s+/).length, 'words'); };
const nav = '[Front page](README.md) · [The world](world.md) · [Districts](districts.md) · [People](people.md) · [The story](story.md) · [Tales and quests](tales.md) · [Relics](relics.md) · [The Undercroft](undercroft.md) · [Trials and Echoes](trials.md)\n\n';

// ---------- the world: lore entries, the open ones first ----------
const open = CODEX.filter((e) => e.unlock === 'start');
const later = [...CODEX, ...SEAM_LORE].filter((e) => e.unlock !== 'start').map((e) => (e.dynamic ? { ...e, text: [`Small things Wren asks about once they have been kept: the stirs of her tea, the colour of the door, the name of her cat, the scar through her mother's eyebrow. Each held detail is kept here as a warm line from Wren. (This entry grows as the Keeper plays.)`] } : e));
write('world.md', `${nav}# The world of Veyra

Everything a new Keeper knows on the first evening, then the lore found later in the year (marked with when it is found).

${open.map((e) => `## ${e.title}\n\n${para(e.text)}`).join('\n\n')}

---

# Lore found during the year

${SPOIL}${later.map((e) => `## ${e.title}\n\n*Found ${unlockText(e.unlock)}.*\n\n${para(e.text)}`).join('\n\n')}
`);

// ---------- districts ----------
write('districts.md', `${nav}# The twelve districts

Veyra is built as twelve great routes, one district a month. Each district keeps one part of the Art, and each is lost in the fog until its gate is passed.

| Month | District | The Art it keeps | Chapter |
| --- | --- | --- | --- |
${MODULES.map((m) => `| ${m.month} | ${m.district} | ${m.title} (${SKILLS[m.skill]?.name || m.skill}) | ${CHAPTERS[m.id]?.title || ''} |`).join('\n')}

${MODULES.map((m) => `## ${m.month}. ${m.district}\n\n**The Art:** ${m.title}. ${m.objective}\n\n**The quest:** ${name(CHAPTERS[m.id]?.quest || '')}${GATE_TALK[m.id] ? `\n\n**Once restored:** "${name(GATE_TALK[m.id][1])}"` : ''}`).join('\n\n')}
`);

// ---------- people ----------
const tier = (min) => (min === 0 ? 'From the start' : `After ${min} gate${min === 1 ? '' : 's'}`);
write('people.md', `${nav}# The people of Veyra

Each person's first paragraph is what you know when you meet them. Later paragraphs are revealed as districts are restored, so they are spoilers.

${CHARACTERS.map((c) => `## ${c.name}\n\n*${c.role}*\n\n${c.tiers.map((t, i) => `${i === 0 ? '' : `**${tier(t.min)} (spoiler):** `}${name(t.text)}`).join('\n\n')}`).join('\n\n')}

${SEAM_PEOPLE.map((c) => `## ${c.name}\n\n*${c.role}*\n\n${c.tiers.map((t, i) => `${i === 0 ? '' : '**Later (spoiler):** '}${name(t.text)}`).join('\n\n')}`).join('\n\n')}

## The Keepers' Circle

The friends who coach a Keeper before and after an Echo battle, never during a question. Each joins once their district is restored.

${Object.entries(COACHES).map(([, c]) => `- **${c.name}**: "${c.before[0]}"`).join('\n')}

## The Forgettings

What the Tide leaves behind when it loosens a memory. They do not bite; they wait to be remembered.

${Object.entries(FORGETTINGS).map(([k, f]) => `- **${f.name}** (${SKILLS[k]?.name || k}): ${f.kind}`).join('\n')}
`);

// ---------- the story ----------
const order = ['prologue', ...MODULES.map((m) => m.id)];
write('story.md', `${nav}# The story, chapter by chapter

${SPOIL}The story is told in a prologue, twelve chapters (one per district, opened by passing its gate), an epilogue for the Year of Keeping, and then Chapter Thirteen, the Seam, with a second epilogue.

${order.map((k) => `## ${CHAPTERS[k].title}\n\n${CHAPTERS[k].quest ? `*${name(CHAPTERS[k].quest)}*\n\n` : ''}${para(CHAPTERS[k].text)}`).join('\n\n')}

## ${EPILOGUE.title}

${para(EPILOGUE.text)}

## The Keepers' Circle (closing scene)

${para(ECHO_HOOK)}

## ${SEAM_CHAPTER.title}

*${SEAM_CHAPTER.quest}*

After the Year of Keeping is complete and the Tide has climbed for a few days, the Great Forgetting stands on the water. It is a battle in four parts (the Hem of the Cloak, the Body of Mist, the Pale Glow and the Stitch) on made-up material. It earns nothing and changes no score. Six of nine days in their places ties the Seam off, and a miss only means trying again another day with a new thread.

${para(SEAM_CHAPTER.text)}

## ${EPILOGUE_TWO.title}

Wren paints her mother from five details that were kept for her: ${FACE_DETAILS.map((d) => d.text).join('; ')}.

${para(EPILOGUE_TWO.text)}
`);

// ---------- weekly tales and side quests ----------
write('tales.md', `${nav}# Weekly tales and side quests

${SPOIL}## Weekly tales

One short tale each week of the year, shown on the map.

${Object.entries(BEATS).map(([w, b]) => `### Week ${w}: ${b.title}\n\n${name(b.text)}`).join('\n\n')}

## Wren's story

Eleven small beats about Wren's family, shown as a Wren card on the Today screen as the year goes by. Weeks later she may ask about one small detail (the number of stirs in her tea, the colour of the door). A miss only means she says it again; a held detail is kept in the Lore.

${WF_BEATS.filter((b) => !b.epilogue).map((b) => `### ${b.title}\n\n*${b.where}, from day ${b.day}.*\n\n${para(b.text)}`).join('\n\n')}

## Side quests

Side quests finish themselves when the Keeper genuinely shows the skill they ask for.

${SIDE_QUESTS.map((q) => `### ${q.title}\n\n*Given by ${q.giver}, ${MODULES.find((m) => m.id === q.module)?.district || q.module}.*\n\n${name(q.hook)}\n\n**When it is done:** ${name(q.done)}`).join('\n\n')}

## ${ECHO_BEAT.title}

${para(ECHO_BEAT.text)}
`);

// ---------- relics ----------
const byKind = (k) => ITEMS.filter((i) => i.kind === k);
write('relics.md', `${nav}# Relics, documents and keepsakes

Every relic is earned by learning, never by time spent. Their stories are part of the lore.

${KINDS.map((k) => `## ${k.name}\n\n${k.blurb}\n\n${byKind(k.id).map((i) => `- **${i.name}**: ${name(i.lore)}`).join('\n')}`).join('\n\n')}
`);

// ---------- the Undercroft ----------
write('undercroft.md', `${nav}# The Undercroft

${SPOIL}Below the Archive is a stair older than the city. Its carved tablets tell the deep history of the river-folk and the Wardens, one floor at a time.

## Tablets

${TABLETS.map((t) => `### Floor ${t.depth}: ${t.title}\n\n${name(t.text)}`).join('\n\n')}

## Guardians

${BOSSES.map((b) => `- **${b.name}** (from floor ${b.from}): ${b.line}`).join('\n')}

## Lost treasures

${TREASURES.map((t) => `- **${t.name}** (floor ${t.depth})${t.desc ? `: ${name(t.desc)}` : ''}`).join('\n')}
`);

// ---------- trials ----------
write('trials.md', `${nav}# District Trials and sealed vaults

Optional trials in the restored districts. The story stays invented; trial material may be real (checked before it ships).

${[...TRIAL_ORDER, ...VAULT_ORDER].map((id) => { const t = TRIALS[id]; return `## ${t.title}\n\n*${t.district}.*\n\n${t.setup}\n\n**If it holds:** ${t.pass}`; }).join('\n\n')}
`);
