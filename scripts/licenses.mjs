// Writes THIRD_PARTY_LICENSES.md and src/data/licenses.js from the licence files of every bundled package.
// Run after changing dependencies: node scripts/licenses.mjs
import fs from 'fs';

const PKGS = [
  ['@fontsource/pixelify-sans', 'Pixelify Sans (font)'],
  ['@fontsource/silkscreen', 'Silkscreen (font)'],
  ['@fontsource/vt323', 'VT323 (font)'],
  ['react', 'React'],
  ['react-dom', 'React DOM'],
  ['scheduler', 'Scheduler (part of React)'],
];
const out = PKGS.map(([name, label]) => {
  const pkg = JSON.parse(fs.readFileSync(`node_modules/${name}/package.json`, 'utf8'));
  const text = fs.readFileSync(`node_modules/${name}/LICENSE`, 'utf8').replace(/\r\n/g, '\n').trim();
  return { name, label, version: pkg.version, license: pkg.license, text };
});
const md = ['# Third-party licences', '', 'Mnemos bundles the following open-source software. All pixel art, characters and story are original to Mnemos.', '',
  ...out.flatMap((x) => [`## ${x.label}: ${x.name} ${x.version} (${x.license})`, '', '```', x.text, '```', ''])].join('\n');
fs.writeFileSync('THIRD_PARTY_LICENSES.md', md);
fs.writeFileSync('src/data/licenses.js', `// Generated by scripts/licenses.mjs. Do not edit by hand.\nexport const LICENSES = ${JSON.stringify(out, null, 1)};\n`);
console.log('licences:', out.map((x) => `${x.name}@${x.version} ${x.license}`).join(', '));
