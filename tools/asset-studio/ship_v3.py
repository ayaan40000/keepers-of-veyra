"""Ships the Nov 8, 2026 painted batch (owner: "push the images generated till now in the game, you choose") WITHOUT touching ship.py or the
generated src/data/art.js: it writes webp files into src/assets/art/ and a second generated manifest src/data/artNew.js that
src/ui/artLookup.jsx merges over art.js (so 'district_M1' here replaces the older night picture of the same id; '-day' pictures stay).
Safe to re-run: it rebuilds everything it owns. Picked by eye: close-ups from out/mapviews/v4/dusk (second-try versions of region/scriptorium/
mirror when painted, else the first try), four times of day of the city from out/mapviews/v3/final.
python tools/asset-studio/ship_v3.py
"""
import json
from pathlib import Path
from PIL import Image

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
ART = ROOT / "src" / "assets" / "art"
V4 = HERE / "out" / "mapviews" / "v4" / "dusk"
V3 = HERE / "out" / "mapviews" / "v3" / "final"

DIST = [("M1", "d01_quay", "Lamplighters' Quay at dusk: lamps, fishermen, carts and boats along the old stone quay."),
        ("M2", "d02_gallery", "The Long Gallery at dusk: a long columned hall, a paved walk and townsfolk."),
        ("M3", "d03_faces", "The Hall of Faces at dusk: a plaza under a hall carved with worn stone faces."),
        ("M4", "d04_counting", "The Counting House at dusk: a tall timber tower, ledgers and a mule with sacks."),
        ("M5", "d05_market", "The Clockwork Market at dusk: a clock tower beside crowded stalls."),
        ("M6", "d06_bridge", "The Tongues Bridge at dusk: a long white arched bridge, barges and shops."),
        ("M7", "d07_scriptorium", "The Scriptorium at dusk: a writing house, a glass spire and a walled garden."),
        ("M8", "d08_stair", "The Tidal Stair at dusk: a zigzag stair, lamps, porters and little waterfalls."),
        ("M9", "d09_mirror", "The Mirror Wards at dusk: crooked houses and courtyards with still pools."),
        ("M10", "d10_roads", "The Open Roads at dusk: the north gate, a milestone and a cobbled road over the heather."),
        ("M11", "d11_amphitheatre", "The Amphitheatre of Echoes at dusk: old stone tiers and a crowd arriving."),
        ("M12", "d12_gate", "The Lethe Gate at dusk: the great sluice works with its iron wheels.")]
VIEWS = [("night", "Veyra at night: a lamp-lit island city under two moons."), ("dusk", "Veyra at dusk: the first lamps lit and the Tide mist rising."),
         ("day", "Veyra by day: an old island city on its hill, busy with carts, boats and people."), ("dawn", "Veyra at dawn: mist on the river and the sea, the city waking.")]


def pick(name):
    p = V4 / f"{name}.png"
    return p if p.exists() else V4 / "_first" / f"{name}.png"


def main():
    (ART / "district").mkdir(parents=True, exist_ok=True)
    (ART / "scene").mkdir(parents=True, exist_ok=True)
    ents, tot = [], 0
    for mid, name, alt in DIST:
        src = pick(name)
        im = Image.open(src).convert("RGB")
        w, h = im.size
        ch = round(w * 9 / 16)
        y0 = max(0, min(h - ch, round((h - ch) * 0.35)))
        im = im.crop((0, y0, w, y0 + ch)).resize((640, 360), Image.LANCZOS)
        f = f"district_{mid}_v3.webp"
        im.save(ART / "district" / f, quality=82, method=6)
        ents.append((f"district_{mid}", "district", f, 640, 360, "dusk", alt)); tot += (ART / "district" / f).stat().st_size
    for t, alt in VIEWS:
        im = Image.open(V3 / f"veyra_{t}.png").convert("RGB").resize((896, 678), Image.LANCZOS)
        f = f"veyra_view_{t}.webp"
        im.save(ART / "scene" / f, quality=80, method=6)
        ents.append((f"veyra_view_{t}", "scene", f, 896, 678, t, alt)); tot += (ART / "scene" / f).stat().st_size
    imps = [f"import n{i} from '../assets/art/{c}/{f}';" for i, (_, c, f, *_r) in enumerate(ents)]
    objs = [f" '{i}': {{ src: n{k}, w: {w}, h: {h}, category: '{c}', model: 'qwen-image-2.1', time: '{t}', alt: {json.dumps(a)} }}," for k, (i, c, f, w, h, t, a) in enumerate(ents)]
    js = ("// Generated by tools/asset-studio/ship_v3.py. Do not edit by hand (re-run the script).\n"
          "// Pictures shipped after the main manifest (src/data/art.js). src/ui/artLookup.jsx merges these over art.js.\n"
          + "\n".join(imps) + "\n\nexport const ART_NEW = {\n" + "\n".join(objs) + "\n};\n")
    (ROOT / "src" / "data" / "artNew.js").write_text(js, encoding="utf-8")
    print(len(ents), "pictures,", tot // 1024, "KB")


if __name__ == "__main__":
    main()
